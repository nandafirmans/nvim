-- Thin wrapper around a dedicated tmux server that hosts the agent sessions.
-- Agents live in tmux so they survive Neovim restarts and crashes.
local M = {}

M.socket = "nvim-agents"

local FORMAT = table.concat({
	"#{session_name}",
	"#{@agent_project}",
	"#{@agent_tool}",
	"#{@agent_index}",
	"#{@agent_cwd}",
	"#{@agent_branch}",
	"#{@agent_status}",
	"#{window_activity}",
	"#{pane_dead}",
	"#{session_created}",
	"#{@agent_label}",
	"#{@agent_activity}",
	"#{@agent_task}",
	"#{@agent_command}",
	"#{@agent_claude_session}",
	"#{@agent_session_id}",
}, "\t")

local conf_path

local function write_conf()
	local dir = vim.fn.stdpath("data") .. "/agents"
	vim.fn.mkdir(dir, "p")
	conf_path = dir .. "/tmux.conf"
	vim.fn.writefile({
		"# Generated by lua/agents/tmux.lua; edits are overwritten.",
		"set -g status off",
		"set -g mouse on",
		"set -g escape-time 0",
		"set -g history-limit 50000",
		'set -g default-terminal "tmux-256color"',
		'set -ga terminal-overrides ",*:RGB"',
		'set -ga terminal-features ",*:extkeys"',
		"set -g extended-keys on",
		"set -g focus-events on",
		"set -g set-clipboard on",
		"set -g allow-passthrough on",
		"set -g window-size latest",
		"set -g remain-on-exit on",
	}, conf_path)
end

function M.cmd(args)
	if not conf_path then
		write_conf()
	end
	return vim.list_extend({ "tmux", "-L", M.socket, "-f", conf_path }, args)
end

function M.available()
	return vim.fn.executable("tmux") == 1
end

-- What a failed start looks like, so callers never see an exception
-- (vim.system throws when tmux is not installed).
local NOT_FOUND = { code = 127, stdout = "", stderr = "tmux is not installed" }

-- Runs a tmux command asynchronously; `cb` gets the vim.system result on the main loop.
function M.run(args, cb, opts)
	local ok = pcall(vim.system, M.cmd(args), vim.tbl_extend("force", { text = true }, opts or {}), function(result)
		if cb then
			vim.schedule(function()
				cb(result)
			end)
		end
	end)
	if not ok and cb then
		vim.schedule(function()
			cb(NOT_FOUND)
		end)
	end
end

function M.run_sync(args)
	local ok, job = pcall(vim.system, M.cmd(args), { text = true })
	if not ok then
		return NOT_FOUND
	end
	return job:wait()
end

-- The command a terminal buffer runs to show one agent. TMUX is unset so it
-- also works when Neovim itself runs inside another tmux.
function M.attach_cmd(name)
	return vim.list_extend({ "env", "-u", "TMUX" }, M.cmd({ "attach-session", "-t", "=" .. name }))
end

function M.list(cb)
	M.run({ "list-sessions", "-F", FORMAT }, function(result)
		local agents = {}
		if result.code == 0 then
			for line in vim.gsplit(result.stdout or "", "\n", { trimempty = true }) do
				local f = vim.split(line, "\t", { plain = true })
				-- Only sessions created by the hub carry @agent_tool.
				if f[3] and f[3] ~= "" then
					table.insert(agents, {
						name = f[1],
						project = f[2],
						tool = f[3],
						index = tonumber(f[4]) or 1,
						cwd = f[5],
						branch = f[6] ~= "" and f[6] or nil,
						hook = f[7] or "",
						activity = tonumber(f[8]) or 0,
						dead = f[9] == "1",
						created = tonumber(f[10]) or 0,
						label = f[11] ~= "" and f[11] or nil,
						activity_text = f[12] ~= "" and f[12] or nil,
						task = f[13] ~= "" and f[13] or nil,
						command = f[14] ~= "" and f[14] or nil,
						claude_session = f[15] ~= "" and f[15] or nil,
						session_id = f[16] ~= "" and f[16] or nil,
					})
				end
			end
		end
		cb(agents)
	end)
end

function M.new_session(opts)
	local result = M.run_sync({
		"new-session",
		"-d",
		"-s",
		opts.name,
		"-c",
		opts.cwd,
		"-x",
		"200",
		"-y",
		"50",
		"-e",
		"NVIM_AGENT_SESSION=" .. opts.name,
		opts.command,
	})
	if result.code ~= 0 then
		return false, vim.trim(result.stderr or "")
	end
	for key, value in pairs(opts.options) do
		M.run_sync({ "set-option", "-t", "=" .. opts.name .. ":", "@agent_" .. key, tostring(value) })
	end
	return true
end

function M.kill(name)
	return M.run_sync({ "kill-session", "-t", "=" .. name })
end

-- Picks the line that best says what a TUI is doing, reading bottom up:
-- skips frames, borders and status bars (lines that start with box-drawing
-- characters) and lines without words, then drops leading spinners and icons.
local function activity_line(lines)
	for i = #lines, 1, -1 do
		local line = vim.trim(lines[i])
		local first = line ~= "" and vim.fn.strgetchar(line, 0) or 0
		local boxed = first >= 0x2500 and first <= 0x257F
		if not boxed then
			line = vim.trim((line:gsub("^[^%w%$%./~@]+", "")))
			local _, letters = line:gsub("%a", "")
			if letters >= 3 then
				return line
			end
		end
	end
end

-- Speech bubble for tabs without hooks, taken from what is on their screen.
function M.last_line(name, cb)
	M.run({ "capture-pane", "-p", "-J", "-t", "=" .. name .. ":" }, function(result)
		cb(activity_line(vim.split(result.stdout or "", "\n", { trimempty = true })))
	end)
end

function M.set_option(name, key, value)
	return M.run_sync({ "set-option", "-t", "=" .. name .. ":", "@agent_" .. key, value })
end

-- Restarts the tab's process; with `command`, runs that instead of the original.
function M.respawn(name, command)
	M.run_sync({ "set-option", "-t", "=" .. name .. ":", "@agent_status", "" })
	local args = { "respawn-pane", "-k", "-t", "=" .. name .. ":" }
	if command then
		table.insert(args, command)
	end
	return M.run_sync(args)
end

-- Sends key names (tmux syntax, e.g. "Enter", "Escape") to the tab.
function M.send_keys(name, ...)
	M.run(vim.list_extend({ "send-keys", "-t", "=" .. name .. ":" }, { ... }))
end

-- Pastes text into the agent's prompt with bracketed paste, so multi-line text
-- is not submitted line by line.
-- `done` runs once the text is in the prompt.
local paste_seq = 0

function M.paste(name, text, done)
	-- One tmux buffer per paste: concurrent pastes (fan-out) must not share one.
	paste_seq = paste_seq + 1
	local buffer = "agents-send-" .. paste_seq
	M.run({ "load-buffer", "-b", buffer, "-" }, function(result)
		if result.code == 0 then
			M.run({ "paste-buffer", "-p", "-d", "-b", buffer, "-t", "=" .. name .. ":" }, done)
		end
	end, { stdin = text })
end

return M
